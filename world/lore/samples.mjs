// node world/lore/samples.mjs > docs/LORE-SAMPLES.md : sample lore drawn from real engine bookings and fixture flights.
import { createRequire } from "module";
const require = createRequire(import.meta.url);
const L = require("./sol-lore.js"), E = require("../engine/sol-page.js"), R = E.R;
const fx = require("../engine/fixtures/fly-baseline.json");
const P = Object.fromEntries(E.PLACES.map((p) => [p.id, p]));
const out = [];
const w = (s = "") => out.push(s);
const card = (h, note) => {
  const o = L.booking(h);
  w(`**${o.headline}** · ${L.parseRider(h.rider).lead}, party of ${h.party}, ${L.PLACE[h.from].name} to ${L.PLACE[h.to].name}${note ? " · " + note : ""}`);
  w(`> ${o.story}`);
  if (o.overheard) w(`> *${o.overheard}*`);
  if (o.place_note) w(`> ${o.place_note.text} *(${o.place_note.tag})*`);
  w(`<sub>${o.tag} · ${o.source} · ${o.version}</sub>`);
  w();
};
w("# Lore samples (generated)");
w();
w("Generated by `node world/lore/samples.mjs` with lore version `" + L.VERSION + "`. Every booking below is a real engine row (`R.HAILS` or `R.hailRow`). Each flight log below is a real fixture flight from `world/engine/fixtures/fly-baseline.json`. The stories are **Fictional**. Bookings and flights are **Simulated**. Place notes tagged Real are qualitative facts about real bodies. Rerun the script after editing the library; do not hand-edit this file.");
w();
const c = L.counts();
w(`Library: ${c.motives} motives, ${c.details} details, ${c.overheard} overheard lines, ${c.features} feature stories, ${c.crew} crew stories, ${c.catalog} catalog stories, ${c.moments} log moments.`);
w();
w("## The five catalog bookings (hand-written)");
w();
for (const h of R.HAILS) card(h);
w("## Season 1 bookings (generated)");
w();
for (let i = 0; i < 16; i++) card(R.hailRow("1", i));
w("## Larger parties (not in the engine yet)");
w();
w("These show what liners or shuttles would carry if capacity grows. The engine's parties are 1 to 3 today, so these bookings are hypothetical inputs, not engine rows.");
w();
const big = [["liner-1", "Noor, a technician", 100, "earth", "titan-dock", "long"], ["liner-2", "Ren, a miner", 64, "ceres-port", "mars-base", "long"],
  ["liner-3", "Hana, a surveyor", 24, "orbital-depot", "lunar-data-center", "quick"], ["liner-4", "Quinn, a pilot", 40, "mars-base", "ceres-port", "long"]];
for (const [id, rider, party, from, to, kind] of big) card({ id, rider, party, from, to, kind }, "hypothetical");
w("## Flight logs with moments");
w();
w("Each line is a recorded event from the fixture flight, in time order, with the moment lore would show beside it. Moments appear only for events the log already holds. On a pickup leg the passengers are still at the dock, so a hold there becomes a waiting moment.");
w();
const picks = [9, 12, 1, 17].map((i) => fx.rides[i]).concat(fx.rides.filter((r) => r.flown.incidents.some((x) => x.kind === "titan_haze" || x.kind === "correction_burn")).slice(0, 2));
picks.forEach((ride, j) => {
  const h = R.BY[ride.hail], key = "fixture-" + j, legs = ride.legs, last = legs[legs.length - 1];
  w(`**${h.title}**, ${ride.car.toUpperCase()}, fixture seed ${ride.seed}`);
  w();
  const F = ride.flown, ev = [];
  ev.push([F.pickup_jd, "boarded at " + L.PLACE[h.from].name, { moment: "boarding", where: h.from }]);
  ev.push([F.ride_depart_jd, "left " + L.PLACE[h.from].name, { moment: "departure", where: h.from }]);
  for (const inc of F.incidents) ev.push([inc.at_jd, inc.kind.replace(/_/g, " ") + " at " + L.PLACE[inc.where].name + " (" + inc.leg + " leg)", { incident: inc.kind, leg: inc.leg, where: inc.where }]);
  const late = (F.delay_hours || 0) > 0.05;
  ev.push([F.arrive_jd, "landed at " + L.PLACE[last.to].name + (late ? ", later than planned" : ""), { moment: late ? "arrival_late" : "arrival", where: last.to }]);
  ev.sort((x, y) => x[0] - y[0]);
  ev.forEach(([, what, e], i) => { const m = L.moment(h, e, key + "|" + i); if (m) w(`- *${what}*: ${m.text}`); });
  w();
});
w("## Real facts from engine numbers");
w();
w("`placeFact` formats only the engine's own `PLACES` fields. Lore stories themselves never carry numbers.");
w();
for (const [id, parent] of [["phobos", "Mars"], ["io", "Jupiter"], ["moon", "Earth"], ["titan", "Saturn"], ["ganymede", "Jupiter"]]) {
  const f = L.placeFact(P[id], parent); if (f) w(`- ${f.text} *(${f.tag}, ${f.source})*`);
}
w();
process.stdout.write(out.join("\n"));
