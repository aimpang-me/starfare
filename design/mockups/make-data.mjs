// Bakes design/mockups/sample-data.js for the website mockups. Every number in it comes from the engine and the
// connector's own game code (connector/src/game.js), the same code path a Grok run takes. Nothing is typed in by hand.
// - SITE: what index.js hands site.html today (sky calendar, planet colours, hails, fleet).
// - RIDES: sample rides flown end to end by a simple "sample bot" (not a player): it takes the hail, uses the
//   engine's par car, plans pickup and ride for energy, quotes the planned fare and arrival, asks at checkpoints
//   after 1 hour and answers each with the default. Each ride carries rideRecord() (the /rides/<run_id>.json shape)
//   plus the planned legs' drawing arcs (heliocentric AU) so a page can replay it.
// Run from the repo root: node design/mockups/make-data.mjs   (needs connector/src/engine, made by connector/build.mjs)
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as G from "../../connector/src/game.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const E = createRequire(import.meta.url)("../../connector/src/engine/sol-page.cjs");
const R = E.R, SKY = G.SKY, SEASON = 13;
const msAt = (season, dayInSeason) => SKY.t0_ms + ((season - 1) * SKY.len_days + dayInSeason) * 1000;

const legFn = (from, to, t, obj, end) => {
  const b = R.planLeg(from, to, t, obj, end);
  const leg = G.computeLeg(E, from, to, t, obj, end);
  leg.arc_au = (b.arc_au || []).map((p) => p.map((x) => +x.toFixed(6)));
  return { leg, cached: false };
};

async function fly(hailId, nowMs, runId) {
  const run = await G.newRun(E, hailId, nowMs, runId);
  const p = (await G.planPickup(E, run, { car: run.par_car, objective: "energy" }, legFn)).leg;
  const r = (await G.planRideLeg(E, run, { after_leg: p.leg_id, objective: "energy" }, legFn)).leg;
  G.checkPad(E, run, { place: R.BY[hailId].to }, nowMs);
  G.spaceWeather(E, run, {}, nowMs);
  let res = G.dispatch(E, run, { pickup_leg: p.leg_id, ride_leg: r.leg_id, quoted_fare_usd: r.fare, quoted_arrival: G.isoJD(r.arr_jd), ask_after_hours: 1 }, nowMs);
  while (res.status === "checkpoint") res = await G.decide(E, run, { checkpoint: res.situation.checkpoint, action: res.situation.default.action }, legFn);
  return run;
}

function pack(run, label) {
  const rec = G.rideRecord(E, run);
  const arcs = {};
  Object.values(run.legs).forEach((L) => { arcs[L.leg_id] = { from: L.from, to: L.to, dep_jd: L.dep_jd, arr_jd: L.arr_jd, arc_au: L.arc_au }; });
  return { label, record: rec, legs: Object.values(run.legs).map(G.legPub.bind(null, E)), arcs, t0_jd: run.t0 };
}

const out = [];
// 1) A Phobos commute that lands into a Mars Base dust storm: scan the season's days for one that stops at a checkpoint.
for (let d = 40; d < 6900; d += 3) {
  const run = await fly("phobos-commute", msAt(SEASON, d), "run_sample" + String(d).padStart(15, "0"));
  if (run.score.log.checkpoints && run.score.log.checkpoints.some((c) => c.kind === "pad_closed")) { out.push(pack(run, "Sample ride with a checkpoint")); break; }
}
// 2) A clean quick hop and 3) the long haul home from Titan, at a fixed day of the same season.
out.push(pack(await fly("iss-crew", msAt(SEASON, 300), "run_sample00000000000000a1"), "Sample quick ride"));
out.push(pack(await fly("titan-home", msAt(SEASON, 300), "run_sample00000000000000b2"), "Sample long haul"));

const site = { sky: SKY, look: (await import("../../connector/src/engine/meta.json", { with: { type: "json" } })).default.look, hails: G.listHails(E), fleet: G.fleet(E) };
const banner = "// Generated by design/mockups/make-data.mjs from the engine and connector/src/game.js. Do not edit by hand.\n";
writeFileSync(join(HERE, "sample-data.js"), banner + "window.SITE = " + JSON.stringify(site) + ";\nwindow.SAMPLE_RIDES = " + JSON.stringify(out) + ";\n");
out.forEach((o) => console.log(o.label, o.record.hail_id, "season", o.record.season, "total", o.record.score.total, "checkpoints", (o.record.log.checkpoints || []).length, "incidents", o.record.score.incidents.length));
